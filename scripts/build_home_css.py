"""Build homepage CSS in its original cascade order. Run after editing shared CSS."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'assets/home-style-sources.json'
OUTPUT = ROOT / 'assets/home.bundle.css'


def expand(path):
    css = (ROOT / path.lstrip('/').split('?')[0]).read_text(encoding='utf-8')
    return re.sub(r'@import\s+url\([\"\']?([^\"\')]+)[\"\']?\)\s*;',
                  lambda m: expand(m[1]), css)


def build():
    parts = [expand(item['path']) if 'path' in item else item['css']
             for item in json.loads(SOURCES.read_text(encoding='utf-8'))]
    # Preserve strings and all whitespace boundaries (including calc operators).
    token = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|/\*[\s\S]*?\*/|\s+')
    css = token.sub(lambda m: m[0] if m[0][0] in "\"'" else ' ', '\n'.join(parts))
    return '/* Generated by scripts/build_home_css.py; edit sources, then rebuild. */\n' + css.strip() + '\n'


if __name__ == '__main__':
    import sys
    result = build()
    if '--check' in sys.argv:
        assert OUTPUT.read_text(encoding='utf-8') == result, 'Run python scripts/build_home_css.py'
    else:
        OUTPUT.write_text(result, encoding='utf-8')
